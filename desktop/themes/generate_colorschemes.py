#!/usr/bin/env python3
"""Generate the M OS Dark and M OS Light KDE color schemes.

The key structure follows the KDE color scheme format (KColorScheme);
the palette values are M OS originals. Output is written into the
mos-branding package tree.
License: LGPL-2.0-or-later (compatible with the KDE color scheme format it targets)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "packages/mos-branding/files/usr/share/color-schemes"

ACCENT = (109, 93, 246)        # M OS Indigo  #6D5DF6
ACCENT_ALT = (56, 189, 248)    # M OS Sky     #38BDF8
NEG, NEU, POS = (239, 68, 68), (245, 158, 11), (16, 185, 129)
VISITED = (167, 139, 250)

PALETTES = {
    "MOSDark": {
        "name": "M OS Dark",
        "fg": (240, 242, 250), "fg_inactive": (152, 160, 184),
        "window": (22, 24, 34), "window_alt": (30, 33, 46),
        "view": (15, 17, 26), "view_alt": (22, 25, 36),
        "button": (34, 37, 52), "button_alt": (44, 48, 66),
        "header": (28, 30, 43), "header_inactive": (22, 24, 34),
        "tooltip": (34, 37, 52),
        "complementary": (12, 14, 22),
        "link": (129, 140, 248),
        "wm_active": (28, 30, 43), "wm_inactive": (22, 24, 34),
        "disabled": (56, 56, 72), "contrast": 4,
    },
    "MOSLight": {
        "name": "M OS Light",
        "fg": (24, 26, 38), "fg_inactive": (100, 108, 128),
        "window": (243, 244, 249), "window_alt": (233, 235, 243),
        "view": (255, 255, 255), "view_alt": (246, 247, 251),
        "button": (250, 250, 253), "button_alt": (236, 238, 246),
        "header": (233, 235, 243), "header_inactive": (243, 244, 249),
        "tooltip": (250, 250, 253),
        "complementary": (22, 24, 34),
        "link": (79, 70, 229),
        "wm_active": (233, 235, 243), "wm_inactive": (243, 244, 249),
        "disabled": (200, 202, 212), "contrast": 4,
    },
}


def rgb(c):
    return ",".join(str(v) for v in c)


def group(name, bg, bg_alt, p, fg=None, fg_inactive=None, selection=False):
    fg = fg or p["fg"]
    fg_inactive = fg_inactive or p["fg_inactive"]
    lines = [f"[{name}]",
             f"BackgroundAlternate={rgb(bg_alt)}",
             f"BackgroundNormal={rgb(bg)}",
             f"DecorationFocus={rgb(ACCENT)}",
             f"DecorationHover={rgb(ACCENT)}",
             f"ForegroundActive={rgb((255, 255, 255) if selection else ACCENT_ALT)}",
             f"ForegroundInactive={rgb(fg_inactive)}",
             f"ForegroundLink={rgb((253, 224, 71) if selection else p['link'])}",
             f"ForegroundNegative={rgb(NEG)}",
             f"ForegroundNeutral={rgb(NEU)}",
             f"ForegroundNormal={rgb(fg)}",
             f"ForegroundPositive={rgb(POS)}",
             f"ForegroundVisited={rgb(VISITED)}",
             ""]
    return "\n".join(lines)


def scheme(key, p):
    white = (255, 255, 255)
    parts = [
        "# M OS color scheme — generated by desktop/themes/generate_colorschemes.py",
        "# SPDX-License-Identifier: LGPL-2.0-or-later",
        "",
        "[ColorEffects:Disabled]", f"Color={rgb(p['disabled'])}", "ColorAmount=0", "ColorEffect=0",
        "ContrastAmount=0.65", "ContrastEffect=1", "IntensityAmount=0.1", "IntensityEffect=2", "",
        "[ColorEffects:Inactive]", "ChangeSelectionColor=true", f"Color={rgb(p['fg_inactive'])}",
        "ColorAmount=0.025", "ColorEffect=2", "ContrastAmount=0.1", "ContrastEffect=2",
        "Enable=false", "IntensityAmount=0", "IntensityEffect=0", "",
        group("Colors:Button", p["button"], p["button_alt"], p),
        group("Colors:Complementary", p["complementary"], p["window_alt"], p,
              fg=(240, 242, 250), fg_inactive=(152, 160, 184)),
        group("Colors:Header", p["header"], p["window"], p),
        group("Colors:Header][Inactive", p["header_inactive"], p["header"], p),
        group("Colors:Selection", ACCENT, (79, 70, 229), p, fg=white,
              fg_inactive=(224, 231, 255), selection=True),
        group("Colors:Tooltip", p["tooltip"], p["window"], p),
        group("Colors:View", p["view"], p["view_alt"], p),
        group("Colors:Window", p["window"], p["window_alt"], p),
        "[General]", f"ColorScheme={key}", f"Name={p['name']}", "shadeSortColumn=true", "",
        "[KDE]", f"contrast={p['contrast']}", "",
        "[WM]", f"activeBackground={rgb(p['wm_active'])}", f"activeBlend={rgb(p['fg'])}",
        f"activeForeground={rgb(p['fg'])}", f"inactiveBackground={rgb(p['wm_inactive'])}",
        f"inactiveBlend={rgb(p['fg_inactive'])}", f"inactiveForeground={rgb(p['fg_inactive'])}", "",
    ]
    return "\n".join(parts)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for key, p in PALETTES.items():
        (OUT / f"{key}.colors").write_text(scheme(key, p), encoding="utf-8")
        print("wrote", key)


if __name__ == "__main__":
    main()
